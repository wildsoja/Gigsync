// Builds public/assets/js/preview-data.js: a snapshot of events and blog posts so the
// site can be previewed by double-clicking public/index.html (no server needed).
// Run: npm run preview-data   (uses your DATA_DIR database, or a fresh one with the sample content)
const fs = require("fs");
const path = require("path");
const os = require("os");

if (!process.env.DATA_DIR) process.env.DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), "wn-preview-"));
const app = require("../server");
const seed = require("../lib/seed");
seed.seedIfEmpty();
seed.seedPosts();

const rel = (v) => JSON.parse(JSON.stringify(v).replace(/"\/(img|uploads|assets)\//g, '"$1/'));

const server = app.listen(0, async () => {
  const base = `http://localhost:${server.address().port}`;
  const get = async (u) => (await fetch(base + u)).json();
  try {
    const config = await get("/api/config");
    const events = await get("/api/events");
    const list = await get("/api/posts");
    const posts = [];
    for (const p of list) { const full = await get("/api/posts/" + encodeURIComponent(p.slug)); delete full.newer; delete full.older; posts.push(full); }
    const data = rel({ config: { ...config, demo: true }, events, posts, builtAt: new Date().toISOString() });
    const out = path.join(__dirname, "..", "public", "assets", "js", "preview-data.js");
    fs.writeFileSync(out, "/* Generated by scripts/build-preview.js. Snapshot used only when the site is opened straight from disk. */\nwindow.WN_PREVIEW = " + JSON.stringify(data) + ";\n");
    console.log(`Wrote ${path.relative(process.cwd(), out)}: ${events.length} event(s), ${posts.length} post(s)`);
  } finally { server.closeAllConnections(); server.close(); }
});
